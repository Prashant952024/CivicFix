"""
CivicFix — D4 Infrastructure Assets & Deficit Scores Ingestion Script
===================================================================
Ingests canonical district physical infrastructure inventories and deficit scores from:
- Datasets_Backend/india/D4_Infrastructure/CivicFix_India_D4_Infrastructure.csv (6,288 rows)
- Datasets_Backend/jharkhand/D4_Infrastructure/CivicFix_Jharkhand_D4_Infrastructure.csv (192 rows)

Generates idempotent SQL seed statements for:
- public.district_infrastructure_assets (6,480 records total: 6,288 INDIA_D4 + 192 JHARKHAND_D4)

Usage:
  python3 scripts/ingest_d4_infrastructure.py
"""

