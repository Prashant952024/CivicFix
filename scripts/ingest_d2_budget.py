#!/usr/bin/env python3
"""
CivicFix — D2 Budget & Fiscal Resources Ingestion Script (Source-Aware Provenance)
================================================================================
Ingests canonical district departmental budgets and financial resources from:
- Datasets_Backend/india/D2_Budget/CivicFix_India_D2_Budget.csv (23,580 rows)
- Datasets_Backend/jharkhand/D2_Budget/CivicFix_Jharkhand_D2_Budget.csv (720 rows)

Generates idempotent SQL seed statements for:
- public.district_department_budgets (24,300 records total: 23,580 INDIA_D2 + 720 JHARKHAND_D2)

Usage:
  python3 scripts/ingest_d2_budget.py
"""

import os
import csv
import sys

